#!/usr/bin/env node
// Pure offline transformation only. This script must never write to /etc/caddy,
// invoke a reload, disable the lego timer, or initiate ACME issuance.
import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const projectRoot = fileURLToPath(new URL('../../', import.meta.url))
const baselinePath = resolve(projectRoot, 'deploy/caddy/zolotoy-dev-production.caddy')
const candidatePath = resolve(projectRoot, 'deploy/caddy/zolotoy-dev-production.automatic-https.caddy')
export const BASELINE_SHA256 = '6b693a30de82e9fbadde371a0b18ea5c5cf9e19fe2ce8d17b372c955c1833144'

function replaceExactlyOnce(source, original, replacement, description) {
  assert.equal(source.split(original).length, 2, 'Unexpected baseline: ' + description)
  return source.replace(original, replacement)
}

export function renderAutomaticHttpsCandidate(baseline) {
  const sha = createHash('sha256').update(baseline).digest('hex')
  assert.equal(sha, BASELINE_SHA256,
    'Refuse to migrate from a different production Caddyfile; re-audit and explicitly update the baseline')

  const legoHttpHandler = [
    '\t# Certificate renewal only; all other HTTP requests redirect to HTTPS.',
    '\thandle /.well-known/acme-challenge/* {',
    '\t\troot * /var/lib/zolotoy-dev-acme/webroot',
    '\t\theader Cache-Control "no-store"',
    '\t\theader X-Robots-Tag "noindex"',
    '\t\tfile_server',
    '\t}',
  ].join('\n')

  let candidate = replaceExactlyOnce(
    baseline,
    '# Generated by scripts/generate-selectel-production.mjs; do not edit directly.',
    '# MIGRATION CANDIDATE ONLY; NOT ACTIVE. Never import before approved TLS cutover.\n' +
      '# Generated offline by scripts/selectel-production/render-caddy-automatic-https.mjs.'
    , 'header')
  candidate = replaceExactlyOnce(
    candidate,
    legoHttpHandler,
    '\t# Caddy Automatic HTTPS handles HTTP-01; retain the explicit 308 redirect.',
    'lego HTTP-01 route')
  candidate = replaceExactlyOnce(
    candidate,
    '\ttls /etc/caddy/zolotoy-dev-tls/current/fullchain.pem /etc/caddy/zolotoy-dev-tls/current/privkey.pem\n',
    '',
    'manual certificate declaration')
  assert(!candidate.includes('/var/lib/zolotoy-dev-acme/webroot'))
  assert(!candidate.includes('tls /etc/caddy/zolotoy-dev-tls/'))
  assert(candidate.includes('redir https://zolotoy.dev{uri} 308'))
  assert(candidate.includes('root * /var/www/zolotoy-dev-production/current'))
  return candidate
}

export async function renderFile({ check = false } = {}) {
  const rendered = renderAutomaticHttpsCandidate(await readFile(baselinePath, 'utf8'))
  if (check) {
    assert.equal(await readFile(candidatePath, 'utf8'), rendered,
      'Automatic HTTPS candidate is stale: regenerate it in the preparation branch')
  } else {
    await writeFile(candidatePath, rendered)
  }
  return candidatePath
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  assert(process.argv.slice(2).every(argument => argument === '--check'),
    'The only supported CLI flag is --check (no VPS operations)')
  const check = process.argv.includes('--check')
  await renderFile({ check })
  console.log('Offline Caddy Automatic HTTPS candidate ' + (check ? 'verified' : 'generated'))
}
