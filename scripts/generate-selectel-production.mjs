#!/usr/bin/env node
// Derive production from the verified staging routes. Every replacement is
// explicit and must match once: a changed staging template requires review.
import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { fileURLToPath, URL } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
const stagingPath = resolve(root, 'deploy/caddy/zolotoy-dev.caddy')
const productionPath = resolve(root, 'deploy/caddy/zolotoy-dev-production.caddy')

function replaceOnce(source, before, after) {
  assert.equal(source.split(before).length, 2, `Expected exactly one production replacement: ${before}`)
  return source.replace(before, after)
}

export function renderProductionConfig(staging) {
  let config = replaceOnce(staging,
    '# Staging only. Import from /etc/caddy/Caddyfile after explicit approval.',
    '# Generated by scripts/generate-selectel-production.mjs; do not edit directly.\n' +
    `# Staging routing source SHA-256: ${createHash('sha256').update(staging).digest('hex')}\n` +
    '# Production only: zolotoy.dev, isolated from the staging deployment user.')
  config = replaceOnce(config,
    'http://origin.zolotoy.dev {\n\theader X-Robots-Tag "noindex,nofollow"\n\tredir https://origin.zolotoy.dev{uri} 308\n}',
    'http://zolotoy.dev {\n\t@operational path /_health /_release\n\theader @operational {\n\t\tX-Robots-Tag "noindex"\n\t\tCache-Control "no-store"\n\t}\n\t# Certificate renewal only; all other HTTP requests redirect to HTTPS.\n\thandle /.well-known/acme-challenge/* {\n\t\troot * /var/lib/zolotoy-dev-acme/webroot\n\t\theader Cache-Control "no-store"\n\t\theader X-Robots-Tag "noindex"\n\t\tfile_server\n\t}\n\thandle {\n\t\tredir https://zolotoy.dev{uri} 308\n\t}\n}')
  config = replaceOnce(config, 'https://origin.zolotoy.dev {', 'https://zolotoy.dev {\n\ttls /etc/caddy/zolotoy-dev-tls/current/fullchain.pem /etc/caddy/zolotoy-dev-tls/current/privkey.pem')
  config = replaceOnce(config, '/var/www/zolotoy-dev/releases/current', '/var/www/zolotoy-dev-production/current')
  config = replaceOnce(config,
    "\t@release expression `{zd_path} == '/_release'`",
    "\t@release expression `{zd_path} == '/_release'`\n\t@operational expression `{zd_path} in ['/_health', '/_release']`")
  config = replaceOnce(config,
    '\troute {\n\t\theader X-Robots-Tag "noindex,nofollow"',
    '\troute {\n\t\t# Operational URLs stay uncached and unindexed, including method errors.\n\t\theader @operational X-Robots-Tag "noindex"\n\t\theader @operational Cache-Control "no-store"')
  config = replaceOnce(config,
    '\t\thandle @unpublished {\n\t\t\theader Cache-Control "no-store"',
    '\t\thandle @unpublished {\n\t\t\theader X-Robots-Tag "noindex"\n\t\t\theader Cache-Control "no-store"')
  config = replaceOnce(config,
    '\t\thandle @demo {\n',
    '\t\thandle @demo {\n\t\t\theader X-Robots-Tag "noindex,follow"\n')
  config = replaceOnce(config,
    '\t\t\t\trespond "Not found" 404',
    '\t\t\t\theader X-Robots-Tag "noindex"\n\t\t\t\trespond "Not found" 404')
  config = replaceOnce(config,
    '\thandle_errors {\n\t\theader X-Robots-Tag "noindex,nofollow"',
    '\thandle_errors {\n\t\theader X-Robots-Tag "noindex"')
  config = replaceOnce(config, 'respond "Staging asset unavailable"', 'respond "Production asset unavailable"')

  assert(!config.includes('origin.zolotoy.dev'), 'Production must not name the staging host')
  assert(!config.includes('/var/www/zolotoy-dev/'), 'Production must not use the staging parent directory')
  assert(!config.includes('www.zolotoy.dev'), 'Do not configure unverified www DNS')
  assert(!config.includes('noindex,nofollow'), 'Production must not inherit the staging blanket robots policy')
  assert(config.includes('tls /etc/caddy/zolotoy-dev-tls/current/fullchain.pem /etc/caddy/zolotoy-dev-tls/current/privkey.pem'), 'Production must use the managed certificate pair')
  assert.deepEqual([...config.matchAll(/^(https?:\/\/[^\s]+) \{/gm)].map((match) => match[1]), ['http://zolotoy.dev', 'https://zolotoy.dev'])
  return config
}

export async function generateProductionConfig({ check = false } = {}) {
  const expected = renderProductionConfig(await readFile(stagingPath, 'utf8'))
  if (check) assert.equal(await readFile(productionPath, 'utf8'), expected, 'Production config is stale; run node scripts/generate-selectel-production.mjs')
  else await writeFile(productionPath, expected)
  return productionPath
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  assert(process.argv.slice(2).every((arg) => arg === '--check'), 'Only --check is supported')
  const check = process.argv.includes('--check')
  await generateProductionConfig({ check })
  console.log(`Production Caddy config ${check ? 'matches the verified staging template' : 'generated'}`)
}
